    public static final String[] BS_MONTH_NAMES = {
            "Baishakh", "Jestha", "Ashadh", "Shrawan",
            "Bhadra",   "Ashwin", "Kartik", "Mangsir",
            "Poush",    "Magh",   "Falgun", "Chaitra"
    };

    /** Immutable BS date value. */
    public record BSDate(int year, int month, int day) {

        public String format() {
            return String.format("%04d-%02d-%02d", year, month, day);
        }

        public String display() {
            return day + " " + BS_MONTH_NAMES[month - 1] + " " + year;
        }
    }

    private BSDateConverter() { }

    // ---------- AD -> BS ----------

    public static BSDate toBS(LocalDate ad) {
        if (ad == null) return null;
        long daysFromAnchor = ChronoUnit.DAYS.between(START_AD, ad);
        if (daysFromAnchor < 0) {
            throw new IllegalArgumentException(
                    "Date is before supported range (AD 1943-04-14)");
        }

        int year = START_BS_YEAR;
        int month = 1;
        long remaining = daysFromAnchor;

        while (true) {
            int idx = year - START_BS_YEAR;
            if (idx < 0 || idx >= BS_MONTH_DAYS.length) {
                throw new IllegalArgumentException(
                        "Date is beyond supported BS range (2099)");
            }
            int daysInMonth = BS_MONTH_DAYS[idx][month - 1];
            if (remaining < daysInMonth) {
                return new BSDate(year, month, (int) remaining + 1);
            }
            remaining -= daysInMonth;
            month++;
            if (month > 12) { month = 1; year++; }
        }
    }

    // ---------- BS -> AD ----------

    public static LocalDate toAD(int bsYear, int bsMonth, int bsDay) {
        int idx = bsYear - START_BS_YEAR;
        if (idx < 0 || idx >= BS_MONTH_DAYS.length) {
            throw new IllegalArgumentException(
                    "BS year " + bsYear + " outside supported range");
        }
        if (bsMonth < 1 || bsMonth > 12) {
            throw new IllegalArgumentException("BS month must be 1-12");
        }
        int maxDay = BS_MONTH_DAYS[idx][bsMonth - 1];
        if (bsDay < 1 || bsDay > maxDay) {
            throw new IllegalArgumentException(
                    "BS day " + bsDay + " invalid for " +
                            BS_MONTH_NAMES[bsMonth - 1] + " " + bsYear +
                            " (has " + maxDay + " days)");
        }

        long days = 0;
        for (int y = START_BS_YEAR; y < bsYear; y++) {
            for (int m : BS_MONTH_DAYS[y - START_BS_YEAR]) days += m;
        }
        for (int m = 1; m < bsMonth; m++) {
            days += BS_MONTH_DAYS[idx][m - 1];
        }
        days += (bsDay - 1);

        return START_AD.plusDays(days);
    }

    // ---------- parse helper ----------

    public static BSDate parse(String text) {
        if (text == null || text.isBlank()) return null;
        String[] parts = text.trim().split("-");
        if (parts.length != 3) return null;
        try {
            int y = Integer.parseInt(parts[0]);
            int m = Integer.parseInt(parts[1]);
            int d = Integer.parseInt(parts[2]);
            toAD(y, m, d);   // validates
            return new BSDate(y, m, d);
        } catch (Exception e) {
            return null;
        }
    }
